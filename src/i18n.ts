export const dictionaries: Record<Lang, Record<TKey, string>> = { en, sq };

export const LANGS: { code: Lang; label: string }[] = [
  { code: "en", label: "English" },
  { code: "sq", label: "Shqip" },
];

export const TContext = createContext<{ lang: Lang; setLang: (l: Lang) => void }>({
  lang: "en",
  setLang: () => undefined,
});

export function useT() {
  const { lang, setLang } = useContext(TContext);
  const t = (key: TKey, vars?: Record<string, string | number>) => {
    let s: string = dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
  return { t, lang, setLang };
}
